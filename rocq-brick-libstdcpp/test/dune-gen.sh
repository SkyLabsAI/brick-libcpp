#!/bin/sh

usage() {
	cat >&2 <<-EOF
		usage: $(basename "$0")

		This will invoke ./cpp2v-dune-gen.sh for every C or C++ file under
		the current directory, sending the dune rules to ${target}.
	EOF
        exit 1
}

[ $# = 0 ] || usage

echo "; DO NOT EDIT: Generated by \"$0${1+ $*}\""

# Temporary: `cpp2v --templates` for only those tests in ./templates.

# The custom mutex conformance suites are compiled and run natively, not by cpp2v.
find . \( -path './mutex/libcpp_tests' -o -path './mutex/scoped_lock_counterexample.cpp' \) -prune -o -name '*.[ch]pp' -print |
LC_ALL=C sort |
while read i; do
  ./cpp2v-dune-gen.sh -s -- $i -- -std=c++20 -stdlib=libstdc++
done
